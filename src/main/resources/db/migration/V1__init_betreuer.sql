CREATE TABLE betreuer
(
    id             UUID NOT NULL,
    name           VARCHAR,
    email          VARCHAR,
    matrikelnummer VARCHAR,
    CONSTRAINT pk_betreuer PRIMARY KEY (id)
);

CREATE TABLE betreuer_fachgebiet
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    bezeichnung VARCHAR,
    betreuer_id UUID                                    NOT NULL,
    CONSTRAINT pk_betreuer_fachgebiet PRIMARY KEY (id)
);

CREATE TABLE betreuer_informationsdatei
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    titel            VARCHAR,
    beschreibung     VARCHAR,
    uploader_name    VARCHAR,
    upload_datum     TIMESTAMP WITHOUT TIME ZONE,
    dateisystem_pfad VARCHAR,
    betreuer_id      UUID                                    NOT NULL,
    CONSTRAINT pk_betreuer_informationsdatei PRIMARY KEY (id)
);

CREATE TABLE betreuer_link
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    url         VARCHAR,
    anzeigetext VARCHAR,
    betreuer_id UUID                                    NOT NULL,
    CONSTRAINT pk_betreuer_link PRIMARY KEY (id)
);

