CREATE TABLE thema
(
    id                   UUID NOT NULL,
    titel                VARCHAR,
    beschreibung_markdown TEXT,
    CONSTRAINT pk_thema PRIMARY KEY (id)
);

CREATE TABLE thema_voraussetzung
(
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    kursbezeichnung        VARCHAR,
    fachgebiet_bezeichnung VARCHAR,
    thema_id               UUID                                    NOT NULL,
    CONSTRAINT pk_thema_voraussetzung PRIMARY KEY (id)
);

CREATE TABLE thema_fachgebiet
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    bezeichnung VARCHAR,
    thema_id    UUID                                    NOT NULL,
    CONSTRAINT pk_thema_fachgebiet PRIMARY KEY (id)
);

CREATE TABLE thema_informationsdatei
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    titel            VARCHAR,
    beschreibung     VARCHAR,
    uploader_name    VARCHAR,
    upload_datum     TIMESTAMP WITHOUT TIME ZONE,
    dateisystem_pfad VARCHAR,
    thema_id         UUID                                    NOT NULL,
    CONSTRAINT pk_thema_informationsdatei PRIMARY KEY (id)
);

CREATE TABLE thema_link
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    url         VARCHAR,
    anzeigetext VARCHAR,
    thema_id    UUID                                    NOT NULL,
    CONSTRAINT pk_thema_link PRIMARY KEY (id)
);

ALTER TABLE thema_voraussetzung
    ADD CONSTRAINT fk_thema_voraussetzung_on_thema FOREIGN KEY (thema_id) REFERENCES thema (id) ON DELETE CASCADE;

ALTER TABLE thema_fachgebiet
    ADD CONSTRAINT fk_thema_fachgebiet_on_thema FOREIGN KEY (thema_id) REFERENCES thema (id) ON DELETE CASCADE;

ALTER TABLE thema_informationsdatei
    ADD CONSTRAINT fk_thema_informationsdatei_on_thema FOREIGN KEY (thema_id) REFERENCES thema (id) ON DELETE CASCADE;

ALTER TABLE thema_link
    ADD CONSTRAINT fk_thema_link_on_thema FOREIGN KEY (thema_id) REFERENCES thema (id) ON DELETE CASCADE;
