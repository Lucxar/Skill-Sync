CREATE TABLE student
(
    id             UUID NOT NULL,
    name           VARCHAR,
    email          VARCHAR,
    matrikelnummer VARCHAR,
    CONSTRAINT pk_student PRIMARY KEY (id)
);

CREATE TABLE student_bestandener_kurs
(
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    kursbezeichnung        VARCHAR,
    bestanden_am           DATE,
    fachgebiet_bezeichnung VARCHAR,
    student_id             UUID                                    NOT NULL,
    CONSTRAINT pk_student_bestandener_kurs PRIMARY KEY (id)
);

CREATE TABLE student_fachgebiet
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    bezeichnung VARCHAR,
    student_id  UUID                                    NOT NULL,
    CONSTRAINT pk_student_fachgebiet PRIMARY KEY (id)
);

ALTER TABLE student_bestandener_kurs
    ADD CONSTRAINT fk_student_bestandener_kurs_on_student FOREIGN KEY (student_id) REFERENCES student (id) ON DELETE CASCADE;

ALTER TABLE student_fachgebiet
    ADD CONSTRAINT fk_student_fachgebiet_on_student FOREIGN KEY (student_id) REFERENCES student (id) ON DELETE CASCADE;
